import fs from 'node:fs';import assert from 'node:assert/strict';
import {createGroupStore,planGroup,applyGroupPlan} from '../runtime/web/outfit-groups.mjs';
fs.mkdirSync('D:/codex',{recursive:true});
const dir=fs.mkdtempSync('D:/codex/group-tests-');
const legacy=[{def:5030,paint:10073,wear:.24,seed:0},{def:7,paint:44,wear:.01,seed:661},{def:5030,paint:10073,wear:.03,seed:0}];
fs.writeFileSync(dir+'/legacy.json',JSON.stringify(legacy));
let store=createGroupStore(dir+'/groups.json',dir+'/legacy.json');
assert.equal(store.list()[0].items.length,3);assert.equal(store.list()[0].items.at(-1).wear,.24);
assert.throws(()=>store.remove('default',true),/默认/);
const group=store.create('测试组合');assert.throws(()=>store.create('测试组合'),/同名/);
assert.throws(()=>store.save(undefined,legacy[0]),/不存在/);
const added=store.save(group.id,legacy[0]);assert.equal(store.get(group.id).items.length,1);
store.removeItem(group.id,added.id);assert.equal(store.get(group.id).items.length,0);
assert.throws(()=>store.remove(group.id,false),/确认/);store.remove(group.id,true);
store=createGroupStore(dir+'/groups.json',dir+'/legacy.json');assert.equal(store.list()[0].items.length,3);
const rows=[{def:7,paint:44},{def:61,paint:1},{def:515,paint:38},{def:5030,paint:10073},{def:9,paint:2},{def:7,paint:1171}];
const lookup=v=>({...v,name:`item ${v.def}`,kind:v.def>5000?'glove':v.def>=500?'knife':'weapon'});
const plan=planGroup(rows,x=>x,lookup);
assert.equal(plan.values.length,5);assert.equal(plan.values.find(i=>i.def===7).paint,1171);
assert.deepEqual(plan.equip.map(i=>i.def),[61,515,7,5030]);
assert.ok(plan.equip.some(i=>i.def===61)&&plan.equip.some(i=>i.def===7),'rifle and pistol retained together');
const calls=[];
const result=await applyGroupPlan(plan,async values=>calls.push(['persist',values.length]),async item=>{calls.push(['refresh',item.def]);return {done:true}});
assert.equal(result.refreshed,true);assert.deepEqual(calls,[['persist',5],['refresh',61],['refresh',515],['refresh',7],['refresh',5030]]);
let callsAfterFailure=0;await assert.rejects(applyGroupPlan(plan,async()=>{throw Error('transaction failed')},async()=>{callsAfterFailure++}));assert.equal(callsAfterFailure,0);
const partial=await applyGroupPlan(plan,async()=>{},async()=>null);assert.equal(partial.refreshed,false);assert.equal(partial.equippedCount,0);
assert.throws(()=>planGroup([],x=>x,lookup),/没有饰品/);
